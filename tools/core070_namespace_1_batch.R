# --- validate pinned R source (NAMESPACE + every cited file) ---------------
# P0: a pre-extracted readback tree under .unlazy/. Contracts with
# source_access = "git-show" (P1): every byte comes from
# `git -C $GLLVMTMB_DIR show <commit>:<path>` into a fresh temp dir; the
# gllvmTMB clone is never checked out or edited.
gllvmtmb_resolved <- NA_character_
if (identical(contract$source_access, "git-show")) {
  gdir <- Sys.getenv("GLLVMTMB_DIR", unset = "")
  if (!nzchar(gdir)) {
    stop("FATAL: GLLVMTMB_DIR must name a local gllvmTMB clone for pin ", pin$name,
         " (read with git show only).")
  }
  gllvmtmb_resolved <- system2("git", c("-C", shQuote(gdir), "rev-parse",
                                        shQuote(paste0(pin$reference_commit, "^{commit}"))),
                               stdout = TRUE)
  stopifnot(identical(gllvmtmb_resolved, pin$reference_commit))
  source_root <- tempfile("core070-namespace-1-src-")
  dir.create(source_root)
  for (rel in c(contract$namespace_pin, names(contract$source_pins))) {
    dest <- file.path(source_root, rel)
    dir.create(dirname(dest), recursive = TRUE, showWarnings = FALSE)
    status <- system2("git", c("-C", shQuote(gdir), "show",
                               shQuote(paste0(pin$reference_commit, ":", rel))),
                      stdout = dest)
    stopifnot(identical(status, 0L))
  }
  namespace_path <- file.path(source_root, contract$namespace_pin)
} else {
  source_root <- file.path(root, ".unlazy/core070-aghq/oracle-source/readback")
  namespace_path <- file.path(root, contract$namespace_pin)
}
