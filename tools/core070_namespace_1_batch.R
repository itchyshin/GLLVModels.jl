# --- pin selection -----------------------------------------------------------
# GLLVM_PARITY_PIN names an entry of tools/core070_oracle_pins.toml (the shared
# pin source, D-294/D-295); unset means tools/parity_oracle.py's _DEFAULT_PIN
# (currently "P0"). Same switch and strict-on-unknown behaviour as the Python
# and Julia sides. The TOML is flat (one [Pn] table of string keys per pin), so
# a line scan suffices and no TOML package is needed.
read_pin <- function(root) {
  oracle_py <- readLines(file.path(root, "tools/parity_oracle.py"), warn = FALSE)
  default_line <- grep('^_DEFAULT_PIN\\s*=\\s*"[A-Za-z0-9_]+"', oracle_py, value = TRUE)
  stopifnot(length(default_line) == 1L)
  default_pin <- sub('^_DEFAULT_PIN\\s*=\\s*"([A-Za-z0-9_]+)".*$', "\\1", default_line)
  raw <- Sys.getenv("GLLVM_PARITY_PIN", unset = NA_character_)
  name <- if (is.na(raw)) default_pin else toupper(trimws(raw))
  lines <- readLines(file.path(root, "tools/core070_oracle_pins.toml"), warn = FALSE)
  hdr <- grep("^\\[[A-Za-z0-9_]+\\]\\s*$", lines)
  found <- sub("^\\[([A-Za-z0-9_]+)\\].*$", "\\1", lines[hdr])
  if (!name %in% found) {
    stop("GLLVM_PARITY_PIN=", raw, " is not a recognized pin. Set it to one of ",
         paste(sort(found), collapse = ", "), " (case/whitespace insensitive), or leave it unset (",
         default_pin, ").")
  }
  k <- match(name, found)
  block <- lines[(hdr[k] + 1L):(c(hdr, length(lines) + 1L)[k + 1L] - 1L)]
  field <- function(key) {
    hit <- grep(paste0("^\\s*", key, "\\s*=\\s*\""), block, value = TRUE)
    stopifnot(length(hit) == 1L)
    sub(paste0("^\\s*", key, "\\s*=\\s*\"([^\"]*)\".*$"), "\\1", hit)
  }
  list(name = name, reference_commit = field("reference_commit"),
       namespace_sha256 = field("namespace_sha256"))
}
