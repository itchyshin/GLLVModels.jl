.pp_get3 <- function(generic, cls) {
  m <- tryCatch(utils::getS3method(generic, cls, envir = asNamespace("gllvmTMB")),
                error = function(e) NULL)
  if (is.null(m)) m <- get(paste0(generic, ".", cls), envir = asNamespace("gllvmTMB"))
  m
}
